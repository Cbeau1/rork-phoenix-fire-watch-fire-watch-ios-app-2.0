#!/usr/bin/env bash
# Regenerates backend/functions/_shared/brandLogo.ts (small JPEG of the official logo on white,
# embedded as base64 so server-side PDFs can brand themselves without network access).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
TMP="$(mktemp -d)"
ffmpeg -loglevel error -y -i "$ROOT/web-phoenix-fire-watch/public/phoenix-logo-brand.png" \
  -filter_complex "color=white:s=1281x1227[bg];[bg][0:v]overlay=format=auto,scale=300:-2" -frames:v 1 -q:v 3 "$TMP/logo.jpg"
read -r W H < <(ffprobe -v error -show_entries stream=width,height -of csv=p=0 "$TMP/logo.jpg" | tr "," " ")
{
  echo "// Generated by backend/scripts/make-brand-logo.sh — do not edit by hand."
  echo "export const BRAND_LOGO = { width: $W, height: $H, jpegBase64: \"$(base64 -w0 "$TMP/logo.jpg")\" };"
} > "$ROOT/backend/functions/_shared/brandLogo.ts"
rm -rf "$TMP"
