#!/bin/sh
# Rebuilds backend/functions/_shared/signatureFont.ts: Great Vibes (OFL) subset to Latin-1, base64-embedded,
# so the daily-report PDF can draw handwritten officer signatures without fetching anything at runtime.
set -e
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
TMP="$(mktemp -d)"
pyftsubset "$ROOT/web-phoenix-fire-watch/public/fonts/GreatVibes-Regular.ttf" \
  --unicodes="U+0020-007E,U+00A0-00FF,U+2018-201D" --layout-features='kern,liga' \
  --no-hinting --desubroutinize --output-file="$TMP/gv.ttf"
B64="$(base64 -w0 "$TMP/gv.ttf")"
printf '/** Great Vibes (SIL Open Font License), Latin subset. Generated by backend/scripts/build-signature-font.sh. */\nexport const SIGNATURE_FONT_BASE64 =\n  "%s";\n' "$B64" > "$ROOT/backend/functions/_shared/signatureFont.ts"
rm -rf "$TMP"
